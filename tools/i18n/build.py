"""Builds the app's strings.xml files and the website's i18n.js from strings.py.

    python3 tools/i18n/build.py
"""
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from strings import S  # noqa: E402

ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
WEB = os.path.abspath(os.path.join(ROOT, "..", "hbrt-agro"))
LANGS = [("en", 1, "values"), ("fa", 2, "values-fa"), ("ps", 3, "values-ps")]

keys = [k for k, *_ in S]
dupes = {k for k in keys if keys.count(k) > 1}
if dupes:
    sys.exit("duplicate keys: " + ", ".join(sorted(dupes)))
for k, en, fa, ps in S:
    n = set(re.findall(r"\{\d\}", en))
    if set(re.findall(r"\{\d\}", fa)) != n or set(re.findall(r"\{\d\}", ps)) != n:
        sys.exit(f"placeholders differ in {k}")


def android(text):
    has_args = bool(re.search(r"\{\d\}", text))
    t = text
    if has_args:
        t = t.replace("%", "%%")
        t = re.sub(r"\{(\d)\}", lambda m: f"%{int(m.group(1)) + 1}$s", t)
    t = t.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    t = t.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    if t.startswith("@") or t.startswith("?"):
        t = "\\" + t
    attr = "" if has_args or "%" not in t else ' formatted="false"'
    return attr, t


for code, col, folder in LANGS:
    out = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- Generated by tools/i18n/build.py from strings.py. Edit strings.py, not this file. -->", "<resources>"]
    for row in S:
        attr, t = android(row[col])
        out.append(f'    <string name="{row[0]}"{attr}>{t}</string>')
    out.append("</resources>")
    d = os.path.join(ROOT, "app", "src", "main", "res", folder)
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, "strings.xml"), "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")

if os.path.isdir(WEB):
    data = {code: {row[0]: row[col] for row in S} for code, col, _ in LANGS}
    with open(os.path.join(WEB, "i18n.js"), "w", encoding="utf-8") as f:
        f.write("/* Generated from Greenhouse_Kotlin/tools/i18n/strings.py. Edit that file, then run build.py. */\n")
        f.write("window.I18N = " + json.dumps(data, ensure_ascii=False, indent=0) + ";\n")
print(f"{len(S)} strings x {len(LANGS)} languages")
